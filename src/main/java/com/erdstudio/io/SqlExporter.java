package com.erdstudio.io;

import com.erdstudio.model.Column;
import com.erdstudio.model.Diagram;
import com.erdstudio.model.Dialect;
import com.erdstudio.model.RefAction;
import com.erdstudio.model.Relation;
import com.erdstudio.model.Table;
import com.erdstudio.model.TableIndex;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/** Generates DDL for a diagram in any of the supported dialects. Building blocks are shared with migrations. */
public final class SqlExporter {

    public record Options(boolean dropTables, boolean comments, boolean mapTypes) {
        public static Options defaults() {
            return new Options(false, true, true);
        }
    }

    private SqlExporter() {}

    public static String export(Diagram d, Dialect dl, Options opt) {
        StringBuilder out = new StringBuilder();
        out.append("-- ").append(d.name).append('\n');
        out.append("-- Generated by ERD Studio for ").append(dl.label).append(" on ")
                .append(LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"))).append("\n\n");
        if (dl == Dialect.SQLITE) out.append("PRAGMA foreign_keys = ON;\n\n");

        List<Table> ordered = topologicalOrder(d);
        Map<String, List<Relation>> fkGroups = groupForeignKeys(d);

        if (opt.dropTables()) {
            for (int i = ordered.size() - 1; i >= 0; i--) {
                out.append("DROP TABLE IF EXISTS ").append(dl.quote(ordered.get(i).name))
                        .append(dl == Dialect.POSTGRESQL ? " CASCADE" : "").append(";\n");
            }
            out.append('\n');
        }

        for (Table t : ordered) {
            if (opt.comments() && !t.comment.isBlank() && dl == Dialect.SQLITE) {
                for (String line : t.comment.split("\\R")) out.append("-- ").append(line).append('\n');
            }
            out.append(createTable(d, t, dl, opt, dl == Dialect.SQLITE ? fkGroups : null)).append("\n\n");
        }

        if (dl != Dialect.SQLITE && !fkGroups.isEmpty()) {
            for (List<Relation> group : fkGroups.values()) out.append(addForeignKey(d, group, dl)).append('\n');
            out.append('\n');
        }

        for (Table t : ordered) {
            for (TableIndex idx : t.indexes) {
                String s = createIndex(t, idx, dl);
                if (s != null) out.append(s).append('\n');
            }
        }

        if (opt.comments()) {
            StringBuilder sb = new StringBuilder();
            for (Table t : ordered) sb.append(commentStatements(t, dl));
            if (sb.length() > 0) out.append('\n').append(sb);
        }
        return out.toString().stripTrailing() + "\n";
    }

    // ------------------------------------------------------------------ building blocks

    /**
     * CREATE TABLE statement (with trailing ';').
     * @param inlineFks for SQLite: FK groups to inline into the table body (null = none)
     */
    public static String createTable(Diagram d, Table t, Dialect dl, Options opt, Map<String, List<Relation>> inlineFks) {
        List<Column> pk = t.primaryKey();
        boolean sqliteInlinePk = dl == Dialect.SQLITE && pk.size() == 1 && pk.get(0).autoIncrement;
        List<String> lines = new ArrayList<>();
        for (Column c : t.columns) lines.add(columnDefinition(c, dl, opt, sqliteInlinePk && c == pk.get(0)));
        if (!pk.isEmpty() && !sqliteInlinePk) {
            List<String> names = new ArrayList<>();
            for (Column c : pk) names.add(dl.quote(c.name));
            String constraint = dl == Dialect.SQLITE || dl == Dialect.MYSQL ? "" : "CONSTRAINT " + dl.quote(pkName(t)) + " ";
            lines.add(constraint + "PRIMARY KEY (" + String.join(", ", names) + ")");
        }
        if (inlineFks != null) {
            for (List<Relation> group : inlineFks.values()) {
                if (group.get(0).fromTableId.equals(t.id)) lines.add(foreignKeyClause(d, group, dl, false));
            }
        }
        StringBuilder out = new StringBuilder("CREATE TABLE ").append(dl.quote(t.name)).append(" (\n");
        for (int i = 0; i < lines.size(); i++) {
            out.append("  ").append(lines.get(i)).append(i < lines.size() - 1 ? "," : "").append('\n');
        }
        out.append(")");
        if (dl == Dialect.MYSQL) {
            out.append(" ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
            if (opt.comments() && !t.comment.isBlank()) out.append(" COMMENT=").append(literal(t.comment));
        }
        return out.append(";").toString();
    }

    /** "name TYPE [IDENTITY] [NOT NULL] [UNIQUE] [DEFAULT x] [COMMENT 'x']" */
    public static String columnDefinition(Column c, Dialect dl, Options opt, boolean sqliteInlinePk) {
        StringBuilder sb = new StringBuilder(dl.quote(c.name)).append(' ');
        if (sqliteInlinePk) return sb.append("INTEGER PRIMARY KEY AUTOINCREMENT").toString();
        String type = columnType(c, dl, opt.mapTypes());
        sb.append(type);
        boolean intType = TypeMapper.isIntegerType(type);
        if (c.autoIncrement && intType) {
            switch (dl) {
                case POSTGRESQL -> sb.append(" GENERATED BY DEFAULT AS IDENTITY");
                case SQLSERVER -> sb.append(" IDENTITY(1,1)");
                default -> { }
            }
        }
        if (c.isRequired()) sb.append(" NOT NULL");
        if (c.autoIncrement && intType && dl == Dialect.MYSQL) sb.append(" AUTO_INCREMENT");
        if (c.unique && !c.primaryKey) sb.append(" UNIQUE");
        String def = defaultValue(c, dl);
        if (def != null) sb.append(" DEFAULT ").append(def);
        if (dl == Dialect.MYSQL && opt.comments() && !c.comment.isBlank()) sb.append(" COMMENT ").append(literal(c.comment));
        return sb.toString();
    }

    public static String columnType(Column c, Dialect dl, boolean mapTypes) {
        return mapTypes ? TypeMapper.map(c.type, dl) : c.type;
    }

    /** Translated DEFAULT expression or null. */
    public static String defaultValue(Column c, Dialect dl) {
        if (c.defaultValue == null || c.defaultValue.isBlank() || c.autoIncrement) return null;
        return TypeMapper.mapDefault(c.defaultValue.trim(), dl);
    }

    public static String foreignKeyClause(Diagram d, List<Relation> group, Dialect dl, boolean named) {
        Relation first = group.get(0);
        Table from = d.table(first.fromTableId), to = d.table(first.toTableId);
        List<String> fromCols = new ArrayList<>(), toCols = new ArrayList<>();
        for (Relation r : group) {
            fromCols.add(dl.quote(from.column(r.fromColumnId).name));
            toCols.add(dl.quote(to.column(r.toColumnId).name));
        }
        StringBuilder sb = new StringBuilder();
        if (named) sb.append("CONSTRAINT ").append(dl.quote(fkName(d, first))).append(' ');
        sb.append("FOREIGN KEY (").append(String.join(", ", fromCols)).append(") REFERENCES ").append(dl.quote(to.name))
                .append(" (").append(String.join(", ", toCols)).append(')');
        appendAction(sb, "DELETE", first.onDelete, dl);
        appendAction(sb, "UPDATE", first.onUpdate, dl);
        return sb.toString();
    }

    public static String addForeignKey(Diagram d, List<Relation> group, Dialect dl) {
        Table from = d.table(group.get(0).fromTableId);
        return "ALTER TABLE " + dl.quote(from.name) + " ADD " + foreignKeyClause(d, group, dl, true) + ";";
    }

    public static String createIndex(Table t, TableIndex idx, Dialect dl) {
        List<String> cols = new ArrayList<>();
        for (String cid : idx.columnIds) {
            Column c = t.column(cid);
            if (c != null) cols.add(dl.quote(c.name));
        }
        if (cols.isEmpty()) return null;
        return "CREATE " + (idx.unique ? "UNIQUE " : "") + "INDEX " + dl.quote(indexName(t, idx))
                + " ON " + dl.quote(t.name) + " (" + String.join(", ", cols) + ");";
    }

    public static String commentStatements(Table t, Dialect dl) {
        StringBuilder sb = new StringBuilder();
        if (dl == Dialect.POSTGRESQL) {
            if (!t.comment.isBlank()) sb.append("COMMENT ON TABLE ").append(dl.quote(t.name)).append(" IS ").append(literal(t.comment)).append(";\n");
            for (Column c : t.columns) {
                if (!c.comment.isBlank()) sb.append("COMMENT ON COLUMN ").append(dl.quote(t.name)).append('.').append(dl.quote(c.name))
                        .append(" IS ").append(literal(c.comment)).append(";\n");
            }
        } else if (dl == Dialect.SQLSERVER) {
            if (!t.comment.isBlank()) sb.append("EXEC sp_addextendedproperty 'MS_Description', N").append(literal(t.comment))
                    .append(", 'SCHEMA', 'dbo', 'TABLE', ").append(literal(t.name)).append(";\n");
            for (Column c : t.columns) {
                if (!c.comment.isBlank()) sb.append("EXEC sp_addextendedproperty 'MS_Description', N").append(literal(c.comment))
                        .append(", 'SCHEMA', 'dbo', 'TABLE', ").append(literal(t.name)).append(", 'COLUMN', ")
                        .append(literal(c.name)).append(";\n");
            }
        }
        return sb.toString();
    }

    private static void appendAction(StringBuilder sb, String event, RefAction action, Dialect dl) {
        if (action == null || action == RefAction.NO_ACTION) return;
        if (action == RefAction.RESTRICT && dl == Dialect.SQLSERVER) return;
        sb.append(" ON ").append(event).append(' ').append(action.sql);
    }

    public static String literal(String s) {
        return "'" + s.replace("'", "''") + "'";
    }

    // ------------------------------------------------------------------ naming (shared with migrations)

    public static String pkName(Table t) {
        return "pk_" + t.name;
    }

    public static String fkName(Diagram d, Relation r) {
        if (r.name != null && !r.name.isBlank()) return r.name;
        Table from = d.table(r.fromTableId);
        Column c = from == null ? null : from.column(r.fromColumnId);
        return "fk_" + (from == null ? "?" : from.name) + "_" + (c == null ? "?" : c.name);
    }

    public static String indexName(Table t, TableIndex idx) {
        if (idx.name != null && !idx.name.isBlank()) return idx.name;
        StringBuilder sb = new StringBuilder(idx.unique ? "uq_" : "idx_").append(t.name);
        for (String cid : idx.columnIds) {
            Column c = t.column(cid);
            if (c != null) sb.append('_').append(c.name);
        }
        return sb.toString();
    }

    /** Relations grouped into (possibly composite) foreign keys. Composite = same name + same table pair. */
    public static Map<String, List<Relation>> groupForeignKeys(Diagram d) {
        Map<String, List<Relation>> groups = new LinkedHashMap<>();
        for (Relation r : d.relations) {
            Table f = d.table(r.fromTableId), t = d.table(r.toTableId);
            if (f == null || t == null || f.column(r.fromColumnId) == null || t.column(r.toColumnId) == null) continue;
            String key = r.name == null || r.name.isBlank() ? r.id : r.fromTableId + "|" + r.toTableId + "|" + r.name;
            groups.computeIfAbsent(key, k -> new ArrayList<>()).add(r);
        }
        return groups;
    }

    /** Parents before children, so CREATE order is valid even with inline FKs. Cycles fall back to model order. */
    public static List<Table> topologicalOrder(Diagram d) {
        List<Table> result = new ArrayList<>();
        Set<String> done = new HashSet<>(), visiting = new HashSet<>();
        for (Table t : d.tables) visit(d, t, done, visiting, result);
        return result;
    }

    private static void visit(Diagram d, Table t, Set<String> done, Set<String> visiting, List<Table> result) {
        if (done.contains(t.id) || visiting.contains(t.id)) return;
        visiting.add(t.id);
        for (Relation r : d.relations) {
            if (r.fromTableId.equals(t.id) && !r.toTableId.equals(t.id)) {
                Table parent = d.table(r.toTableId);
                if (parent != null) visit(d, parent, done, visiting, result);
            }
        }
        visiting.remove(t.id);
        done.add(t.id);
        result.add(t);
    }
}

package com.erdstudio.io;

import com.erdstudio.model.Column;
import com.erdstudio.model.Diagram;
import com.erdstudio.model.Dialect;
import com.erdstudio.model.Relation;
import com.erdstudio.model.Table;
import com.erdstudio.model.TableIndex;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;

/**
 * Diffs two versions of a diagram and writes the ALTER script that turns {@code from} into {@code to}.
 * Tables and columns are matched by their internal ids, so renames are detected as renames
 * (not as drop + create, which would lose data).
 */
public final class MigrationGenerator {

    private static final SqlExporter.Options OPT = new SqlExporter.Options(false, true, true);

    private final Diagram from, to;
    private final Dialect dl;
    private final List<String> out = new ArrayList<>();
    private final List<String> notes = new ArrayList<>();

    private MigrationGenerator(Diagram from, Diagram to, Dialect dl) {
        this.from = from;
        this.to = to;
        this.dl = dl;
    }

    public static String generate(Diagram from, Diagram to, Dialect dialect, String fromLabel, String toLabel) {
        MigrationGenerator g = new MigrationGenerator(from, to, dialect);
        g.run();
        StringBuilder sb = new StringBuilder();
        sb.append("-- Migration: ").append(fromLabel).append("  ->  ").append(toLabel).append('\n');
        sb.append("-- ").append(dialect.label).append(", generated by ERD Studio on ")
                .append(LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"))).append('\n');
        sb.append("-- Review before running it on a database with real data.\n\n");
        if (g.out.isEmpty()) {
            sb.append("-- No schema changes.\n");
            return sb.toString();
        }
        if (!g.notes.isEmpty()) {
            for (String n : g.notes) sb.append("-- NOTE: ").append(n).append('\n');
            sb.append('\n');
        }
        if (dialect == Dialect.POSTGRESQL || dialect == Dialect.SQLITE) sb.append("BEGIN;\n\n");
        if (dialect == Dialect.SQLSERVER) sb.append("BEGIN TRANSACTION;\n\n");
        for (String s : g.out) sb.append(s).append(s.endsWith("\n") ? "" : "\n");
        if (dialect == Dialect.POSTGRESQL || dialect == Dialect.SQLITE) sb.append("\nCOMMIT;\n");
        if (dialect == Dialect.SQLSERVER) sb.append("\nCOMMIT TRANSACTION;\n");
        return sb.toString();
    }

    private String q(String s) { return dl.quote(s); }

    private void emit(String sql) { out.add(sql); }

    private void section(String title) { out.add("\n-- " + title); }

    // ------------------------------------------------------------------ main

    private void run() {
        Map<String, Table> oldT = new LinkedHashMap<>(), newT = new LinkedHashMap<>();
        for (Table t : from.tables) oldT.put(t.id, t);
        for (Table t : to.tables) newT.put(t.id, t);

        Set<String> dropped = new LinkedHashSet<>(oldT.keySet());
        dropped.removeAll(newT.keySet());
        Set<String> created = new LinkedHashSet<>(newT.keySet());
        created.removeAll(oldT.keySet());
        Set<String> common = new LinkedHashSet<>(oldT.keySet());
        common.retainAll(newT.keySet());

        Map<String, FkDef> oldFks = fks(from), newFks = fks(to);

        // SQLite can't alter much: tables with structural changes are rebuilt instead
        Set<String> rebuild = new LinkedHashSet<>();
        if (dl == Dialect.SQLITE) {
            for (String id : common) if (needsSqliteRebuild(oldT.get(id), newT.get(id), oldFks, newFks)) rebuild.add(id);
            if (!rebuild.isEmpty()) emit("PRAGMA foreign_keys = OFF;");
        }

        // 1. drop foreign keys that disappear or change
        if (dl != Dialect.SQLITE) {
            List<String> drops = new ArrayList<>();
            for (Map.Entry<String, FkDef> e : oldFks.entrySet()) {
                FkDef o = e.getValue(), n = newFks.get(e.getKey());
                if (dropped.contains(o.fromTableId)) continue; // goes away with its table
                if (n == null || !n.sameAs(o)) drops.add(dropFk(o));
            }
            if (!drops.isEmpty()) { section("Drop changed / removed foreign keys"); drops.forEach(this::emit); }
        }

        // 2. drop indexes that disappear or change (on surviving tables)
        List<String> idxDrops = new ArrayList<>();
        for (String id : common) {
            if (rebuild.contains(id)) continue;
            Table o = oldT.get(id), n = newT.get(id);
            for (TableIndex oi : o.indexes) {
                TableIndex ni = findIndex(n, oi.id);
                if (ni == null || !indexDef(o, oi).equals(indexDef(n, ni))) idxDrops.add(dropIndex(o, oi));
            }
        }
        if (!idxDrops.isEmpty()) { section("Drop changed / removed indexes"); idxDrops.forEach(this::emit); }

        // 3. drop tables (children first)
        if (!dropped.isEmpty()) {
            section("Drop tables");
            List<Table> order = SqlExporter.topologicalOrder(from);
            for (int i = order.size() - 1; i >= 0; i--) {
                Table t = order.get(i);
                if (dropped.contains(t.id)) emit("DROP TABLE " + q(t.name) + ";");
            }
        }

        // 4. rename tables
        List<String> renames = new ArrayList<>();
        for (String id : common) {
            Table o = oldT.get(id), n = newT.get(id);
            if (!o.name.equals(n.name) && !rebuild.contains(id)) renames.add(renameTable(o.name, n.name));
        }
        if (!renames.isEmpty()) { section("Rename tables"); renames.forEach(this::emit); }

        // 5. create tables
        if (!created.isEmpty()) {
            section("New tables");
            Map<String, List<Relation>> groups = dl == Dialect.SQLITE ? SqlExporter.groupForeignKeys(to) : null;
            for (Table t : SqlExporter.topologicalOrder(to)) {
                if (!created.contains(t.id)) continue;
                emit(SqlExporter.createTable(to, t, dl, OPT, groups));
                String c = SqlExporter.commentStatements(t, dl);
                if (!c.isEmpty()) emit(c.stripTrailing());
                for (TableIndex idx : t.indexes) {
                    String s = SqlExporter.createIndex(t, idx, dl);
                    if (s != null) emit(s);
                }
            }
        }

        // 6. column changes
        for (String id : common) {
            if (rebuild.contains(id)) {
                sqliteRebuild(oldT.get(id), newT.get(id));
                continue;
            }
            alterColumns(oldT.get(id), newT.get(id));
        }

        // 7. create new / changed indexes
        List<String> idxAdds = new ArrayList<>();
        for (String id : common) {
            if (rebuild.contains(id)) continue;
            Table o = oldT.get(id), n = newT.get(id);
            for (TableIndex ni : n.indexes) {
                TableIndex oi = findIndex(o, ni.id);
                if (oi == null || !indexDef(o, oi).equals(indexDef(n, ni))) {
                    String s = SqlExporter.createIndex(n, ni, dl);
                    if (s != null) idxAdds.add(s);
                }
            }
        }
        if (!idxAdds.isEmpty()) { section("New / changed indexes"); idxAdds.forEach(this::emit); }

        // 8. add foreign keys
        if (dl != Dialect.SQLITE) {
            List<String> adds = new ArrayList<>();
            for (Map.Entry<String, FkDef> e : newFks.entrySet()) {
                FkDef n = e.getValue(), o = oldFks.get(e.getKey());
                if (o == null || !o.sameAs(n) || created.contains(n.fromTableId)) {
                    adds.add(SqlExporter.addForeignKey(to, n.group, dl));
                }
            }
            if (!adds.isEmpty()) { section("New / changed foreign keys"); adds.forEach(this::emit); }
        }

        if (dl == Dialect.SQLITE && !rebuild.isEmpty()) emit("\nPRAGMA foreign_keys = ON;");
    }

    // ------------------------------------------------------------------ columns

    private void alterColumns(Table o, Table n) {
        String t = q(n.name);
        List<String> s = new ArrayList<>();

        // renamed columns first, so later statements can use the new names
        for (Column nc : n.columns) {
            Column oc = o.column(nc.id);
            if (oc != null && !oc.name.equals(nc.name)) s.add(renameColumn(n.name, oc.name, nc.name));
        }
        // dropped columns
        for (Column oc : o.columns) {
            if (n.column(oc.id) != null) continue;
            if (dl == Dialect.SQLSERVER) s.add(dropDefaultMssql(n.name, oc.name));
            s.add("ALTER TABLE " + t + " DROP COLUMN " + q(oc.name) + ";");
        }
        // added columns
        for (Column nc : n.columns) {
            if (o.column(nc.id) != null) continue;
            Column add = nc;
            if (nc.primaryKey) { add = nc.copy(false); add.primaryKey = false; add.notNull = nc.notNull || nc.primaryKey; }
            String def = SqlExporter.columnDefinition(add, dl, OPT, false);
            if (dl == Dialect.SQLSERVER) s.add("ALTER TABLE " + t + " ADD " + def + ";");
            else s.add("ALTER TABLE " + t + " ADD COLUMN " + def + ";");
            if (add.isRequired() && SqlExporter.defaultValue(add, dl) == null && !add.autoIncrement) {
                notes.add(n.name + "." + nc.name + " is NOT NULL without a default; this fails if the table already has rows.");
            }
        }
        // changed columns
        for (Column nc : n.columns) {
            Column oc = o.column(nc.id);
            if (oc == null) continue;
            alterColumn(n, oc, nc, s);
        }
        // primary key
        List<String> oldPk = pkNames(o), newPk = pkIds(n);
        if (!pkIds(o).equals(newPk)) {
            if (!oldPk.isEmpty()) {
                switch (dl) {
                    case MYSQL -> s.add("ALTER TABLE " + t + " DROP PRIMARY KEY;");
                    default -> s.add("ALTER TABLE " + t + " DROP CONSTRAINT " + (dl == Dialect.POSTGRESQL ? "IF EXISTS " : "")
                            + q(SqlExporter.pkName(o)) + ";");
                }
            }
            List<String> cols = new ArrayList<>();
            for (Column c : n.primaryKey()) cols.add(q(c.name));
            if (!cols.isEmpty()) {
                String name = dl == Dialect.MYSQL ? "" : "CONSTRAINT " + q(SqlExporter.pkName(n)) + " ";
                s.add("ALTER TABLE " + t + " ADD " + name + "PRIMARY KEY (" + String.join(", ", cols) + ");");
            }
        }
        // comments
        if (dl == Dialect.POSTGRESQL) {
            if (!Objects.equals(o.comment, n.comment)) {
                s.add("COMMENT ON TABLE " + t + " IS " + (n.comment.isBlank() ? "NULL" : SqlExporter.literal(n.comment)) + ";");
            }
            for (Column nc : n.columns) {
                Column oc = o.column(nc.id);
                if (oc != null && !Objects.equals(oc.comment, nc.comment)) {
                    s.add("COMMENT ON COLUMN " + t + "." + q(nc.name) + " IS "
                            + (nc.comment.isBlank() ? "NULL" : SqlExporter.literal(nc.comment)) + ";");
                }
            }
        } else if (dl == Dialect.MYSQL && !Objects.equals(o.comment, n.comment)) {
            s.add("ALTER TABLE " + t + " COMMENT = " + SqlExporter.literal(n.comment) + ";");
        }
        if (!s.isEmpty()) {
            section("Table " + n.name);
            s.forEach(this::emit);
        }
    }

    private void alterColumn(Table n, Column oc, Column nc, List<String> s) {
        String t = q(n.name), c = q(nc.name);
        String oType = SqlExporter.columnType(oc, dl, true), nType = SqlExporter.columnType(nc, dl, true);
        boolean typeChanged = !oType.equalsIgnoreCase(nType);
        boolean nullChanged = oc.isRequired() != nc.isRequired();
        String oDef = SqlExporter.defaultValue(oc, dl), nDef = SqlExporter.defaultValue(nc, dl);
        boolean defChanged = !Objects.equals(oDef, nDef);
        boolean uniqueChanged = (oc.unique && !oc.primaryKey) != (nc.unique && !nc.primaryKey);
        boolean aiChanged = oc.autoIncrement != nc.autoIncrement;
        boolean commentChanged = !Objects.equals(oc.comment, nc.comment);
        if (!typeChanged && !nullChanged && !defChanged && !uniqueChanged && !aiChanged && !(commentChanged && dl == Dialect.MYSQL)) return;

        switch (dl) {
            case POSTGRESQL -> {
                if (typeChanged) s.add("ALTER TABLE " + t + " ALTER COLUMN " + c + " TYPE " + nType + " USING " + c + "::" + nType + ";");
                if (nullChanged) s.add("ALTER TABLE " + t + " ALTER COLUMN " + c + (nc.isRequired() ? " SET NOT NULL;" : " DROP NOT NULL;"));
                if (defChanged) s.add("ALTER TABLE " + t + " ALTER COLUMN " + c + (nDef == null ? " DROP DEFAULT;" : " SET DEFAULT " + nDef + ";"));
                if (aiChanged) s.add("ALTER TABLE " + t + " ALTER COLUMN " + c + (nc.autoIncrement
                        ? " ADD GENERATED BY DEFAULT AS IDENTITY;" : " DROP IDENTITY IF EXISTS;"));
                if (uniqueChanged) {
                    String uq = q(n.name + "_" + nc.name + "_key");
                    s.add(nc.unique ? "ALTER TABLE " + t + " ADD CONSTRAINT " + uq + " UNIQUE (" + c + ");"
                            : "ALTER TABLE " + t + " DROP CONSTRAINT IF EXISTS " + uq + ";");
                }
            }
            case MYSQL -> {
                if (typeChanged || nullChanged || defChanged || aiChanged || commentChanged) {
                    Column def = nc.copy(false);
                    def.unique = false; // handled separately below
                    if (def.primaryKey) { def.primaryKey = false; def.notNull = true; }
                    s.add("ALTER TABLE " + t + " MODIFY COLUMN " + SqlExporter.columnDefinition(def, dl, OPT, false) + ";");
                }
                if (uniqueChanged) {
                    s.add(nc.unique ? "ALTER TABLE " + t + " ADD UNIQUE INDEX " + q(nc.name) + " (" + c + ");"
                            : "ALTER TABLE " + t + " DROP INDEX " + q(oc.name) + ";");
                }
            }
            case SQLSERVER -> {
                if (typeChanged || nullChanged) {
                    s.add("ALTER TABLE " + t + " ALTER COLUMN " + c + " " + nType + (nc.isRequired() ? " NOT NULL" : " NULL") + ";");
                }
                if (defChanged) {
                    s.add(dropDefaultMssql(n.name, nc.name));
                    if (nDef != null) s.add("ALTER TABLE " + t + " ADD DEFAULT " + nDef + " FOR " + c + ";");
                }
                if (uniqueChanged) {
                    if (nc.unique) s.add("ALTER TABLE " + t + " ADD CONSTRAINT " + q("uq_" + n.name + "_" + nc.name) + " UNIQUE (" + c + ");");
                    else s.add(dropUniqueMssql(n.name, nc.name));
                }
                if (aiChanged) notes.add("SQL Server can't add/remove IDENTITY on " + n.name + "." + nc.name
                        + " with ALTER; recreate the column or table manually.");
            }
            case SQLITE -> { } // handled by rebuild
        }
    }

    // ------------------------------------------------------------------ SQLite rebuild

    private boolean needsSqliteRebuild(Table o, Table n, Map<String, FkDef> oldFks, Map<String, FkDef> newFks) {
        if (!pkIds(o).equals(pkIds(n))) return true;
        for (Column nc : n.columns) {
            Column oc = o.column(nc.id);
            if (oc == null) {
                if (nc.primaryKey || nc.unique || (nc.isRequired() && SqlExporter.defaultValue(nc, dl) == null)) return true;
                continue;
            }
            if (!SqlExporter.columnType(oc, dl, true).equalsIgnoreCase(SqlExporter.columnType(nc, dl, true))
                    || oc.isRequired() != nc.isRequired() || oc.unique != nc.unique || oc.autoIncrement != nc.autoIncrement
                    || !Objects.equals(SqlExporter.defaultValue(oc, dl), SqlExporter.defaultValue(nc, dl))) return true;
        }
        for (Column oc : o.columns) if (n.column(oc.id) == null && (oc.primaryKey || oc.unique)) return true;
        // FK changes on this table
        Set<String> keys = new LinkedHashSet<>(oldFks.keySet());
        keys.addAll(newFks.keySet());
        for (String k : keys) {
            FkDef a = oldFks.get(k), b = newFks.get(k);
            boolean mine = (a != null && a.fromTableId.equals(o.id)) || (b != null && b.fromTableId.equals(n.id));
            if (!mine) continue;
            if (a == null || b == null || !a.sameAs(b)) return true;
        }
        return false;
    }

    private void sqliteRebuild(Table o, Table n) {
        section("Rebuild " + n.name + " (SQLite can't alter columns or constraints in place)");
        String tmp = "_new_" + n.name;
        Table copy = new Table(tmp);
        copy.id = n.id;
        copy.columns = n.columns;
        copy.comment = n.comment;
        Map<String, List<Relation>> groups = SqlExporter.groupForeignKeys(to);
        Diagram tmpDiagram = new Diagram();
        tmpDiagram.tables.addAll(to.tables);
        tmpDiagram.tables.replaceAll(t -> t.id.equals(n.id) ? copy : t);
        tmpDiagram.relations.addAll(to.relations);
        // relations pointing at this table should still reference the real name
        emit(SqlExporter.createTable(tmpDiagram, copy, dl, OPT, groupsFor(groups, n.id)).replace(
                "REFERENCES " + q(tmp), "REFERENCES " + q(n.name)));
        List<String> dst = new ArrayList<>(), src = new ArrayList<>();
        for (Column nc : n.columns) {
            Column oc = o.column(nc.id);
            if (oc == null) continue;
            dst.add(q(nc.name));
            src.add(q(oc.name));
        }
        if (!dst.isEmpty()) {
            emit("INSERT INTO " + q(tmp) + " (" + String.join(", ", dst) + ") SELECT " + String.join(", ", src) + " FROM " + q(o.name) + ";");
        }
        emit("DROP TABLE " + q(o.name) + ";");
        emit("ALTER TABLE " + q(tmp) + " RENAME TO " + q(n.name) + ";");
        for (TableIndex idx : n.indexes) {
            String s = SqlExporter.createIndex(n, idx, dl);
            if (s != null) emit(s);
        }
    }

    private static Map<String, List<Relation>> groupsFor(Map<String, List<Relation>> all, String tableId) {
        Map<String, List<Relation>> out = new LinkedHashMap<>();
        for (Map.Entry<String, List<Relation>> e : all.entrySet()) {
            if (e.getValue().get(0).fromTableId.equals(tableId)) out.put(e.getKey(), e.getValue());
        }
        return out;
    }

    // ------------------------------------------------------------------ helpers

    private String renameTable(String oldName, String newName) {
        return switch (dl) {
            case MYSQL -> "RENAME TABLE " + q(oldName) + " TO " + q(newName) + ";";
            case SQLSERVER -> "EXEC sp_rename " + SqlExporter.literal(oldName) + ", " + SqlExporter.literal(newName) + ";";
            default -> "ALTER TABLE " + q(oldName) + " RENAME TO " + q(newName) + ";";
        };
    }

    private String renameColumn(String table, String oldName, String newName) {
        if (dl == Dialect.SQLSERVER) {
            return "EXEC sp_rename " + SqlExporter.literal(table + "." + oldName) + ", " + SqlExporter.literal(newName) + ", 'COLUMN';";
        }
        return "ALTER TABLE " + q(table) + " RENAME COLUMN " + q(oldName) + " TO " + q(newName) + ";";
    }

    private String dropFk(FkDef fk) {
        String t = q(fk.fromTableName);
        return switch (dl) {
            case MYSQL -> "ALTER TABLE " + t + " DROP FOREIGN KEY " + q(fk.name) + ";";
            case POSTGRESQL -> "ALTER TABLE " + t + " DROP CONSTRAINT IF EXISTS " + q(fk.name) + ";";
            default -> "ALTER TABLE " + t + " DROP CONSTRAINT " + q(fk.name) + ";";
        };
    }

    private String dropIndex(Table t, TableIndex idx) {
        String name = q(SqlExporter.indexName(t, idx));
        return switch (dl) {
            case MYSQL, SQLSERVER -> "DROP INDEX " + name + " ON " + q(t.name) + ";";
            case POSTGRESQL -> "DROP INDEX IF EXISTS " + name + ";";
            case SQLITE -> "DROP INDEX IF EXISTS " + name + ";";
        };
    }

    private String dropDefaultMssql(String table, String column) {
        return "DECLARE @df_" + safe(table + "_" + column) + " sysname = (SELECT d.name FROM sys.default_constraints d "
                + "JOIN sys.columns c ON d.parent_object_id = c.object_id AND d.parent_column_id = c.column_id "
                + "WHERE d.parent_object_id = OBJECT_ID(" + SqlExporter.literal(table) + ") AND c.name = " + SqlExporter.literal(column) + ");\n"
                + "IF @df_" + safe(table + "_" + column) + " IS NOT NULL EXEC('ALTER TABLE " + q(table).replace("'", "''")
                + " DROP CONSTRAINT [' + @df_" + safe(table + "_" + column) + " + ']');";
    }

    private String dropUniqueMssql(String table, String column) {
        String v = "@uq_" + safe(table + "_" + column);
        return "DECLARE " + v + " sysname = (SELECT TOP 1 kc.name FROM sys.key_constraints kc "
                + "JOIN sys.index_columns ic ON ic.object_id = kc.parent_object_id AND ic.index_id = kc.unique_index_id "
                + "JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id "
                + "WHERE kc.type = 'UQ' AND kc.parent_object_id = OBJECT_ID(" + SqlExporter.literal(table) + ") AND c.name = "
                + SqlExporter.literal(column) + ");\n"
                + "IF " + v + " IS NOT NULL EXEC('ALTER TABLE " + q(table).replace("'", "''") + " DROP CONSTRAINT [' + " + v + " + ']');";
    }

    private static String safe(String s) {
        return s.replaceAll("[^A-Za-z0-9_]", "_");
    }

    private static TableIndex findIndex(Table t, String id) {
        for (TableIndex i : t.indexes) if (i.id.equals(id)) return i;
        return null;
    }

    private static String indexDef(Table t, TableIndex idx) {
        StringBuilder sb = new StringBuilder(SqlExporter.indexName(t, idx)).append(idx.unique ? "|U|" : "|N|");
        for (String cid : idx.columnIds) {
            Column c = t.column(cid);
            if (c != null) sb.append(c.name).append(',');
        }
        return sb.toString();
    }

    private static List<String> pkIds(Table t) {
        List<String> ids = new ArrayList<>();
        for (Column c : t.primaryKey()) ids.add(c.id);
        return ids;
    }

    private static List<String> pkNames(Table t) {
        List<String> ids = new ArrayList<>();
        for (Column c : t.primaryKey()) ids.add(c.name);
        return ids;
    }

    /** A FK group with everything that would show up in its DDL. */
    private record FkDef(String key, String name, String fromTableId, String fromTableName, String signature, List<Relation> group) {
        boolean sameAs(FkDef o) {
            return signature.equals(o.signature);
        }
    }

    private static Map<String, FkDef> fks(Diagram d) {
        Map<String, FkDef> out = new LinkedHashMap<>();
        for (Map.Entry<String, List<Relation>> e : SqlExporter.groupForeignKeys(d).entrySet()) {
            List<Relation> g = e.getValue();
            Relation first = g.get(0);
            Table f = d.table(first.fromTableId), t = d.table(first.toTableId);
            StringBuilder sig = new StringBuilder(SqlExporter.fkName(d, first)).append('|').append(f.name).append('|').append(t.name);
            for (Relation r : g) sig.append('|').append(f.column(r.fromColumnId).name).append('>').append(t.column(r.toColumnId).name);
            sig.append('|').append(first.onDelete).append('|').append(first.onUpdate);
            String key = first.name == null || first.name.isBlank() ? first.id : e.getKey();
            out.put(key, new FkDef(key, SqlExporter.fkName(d, first), f.id, f.name, sig.toString(), g));
        }
        return out;
    }
}
